assert.equal(routing.normalizeDeskhotel({dataVenda:'10/09/2026',origin:'Motor - Alice'}).targetSheet,routing.CHANNELS_SHEET);
assert.equal(routing.normalizeDeskhotel({dataVenda:'08/09/2026',origin:'Depto_Reservas - Tatiana Vieira'}).vendedor,'Tatiana Vieira');
const existingExternal={dataVenda:'08/09/2026',codigo:'CR-A',hotel:'H',canal:'Airbnb',fonte:'DESKHOTEL'};
assert.throws(()=>routing.assertSalesWrite({dataVenda:'08/09/2026',codigo:'CR-A',hotel:'H',canal:'',vendedor:'Rogério Mendes'},routing.SELLERS_SHEET,[existingExternal]),/ja cadastrada/);
assert.throws(()=>routing.assertSalesWrite({dataVenda:'08/09/2026',codigo:'CR-B',hotel:'H',canal:'',vendedor:''},routing.SELLERS_SHEET),/sem vendedor/);
assert.throws(()=>routing.assertSalesWrite({...existingExternal,codigo:'CR-C'},routing.CHANNELS_SHEET),/Origem DeskHotel ausente/);
assert.doesNotThrow(()=>routing.assertSalesWrite({...desk,codigo:'CR-D',hotel:'H'},routing.CHANNELS_SHEET));
assert.doesNotThrow(()=>routing.assertSalesWrite({...alice,codigo:'CR-E',hotel:'H'},routing.CHANNELS_SHEET));
