assert.equal(alice.vendedor,'Alice (Robo)');
assert.equal(alice.formaPagamento,'Cartao credito');
const shortAlice = routing.normalizeDeskhotel({dataVenda:'12/09/2026',origin:'Alice',hotel:'SUEDS CABRALIA',status:'Confirmada'});
assert.equal(shortAlice.canal,'Robo');
assert.equal(shortAlice.vendedor,'Alice (Robo)');
assert.equal(shortAlice.targetSheet,routing.CHANNELS_SHEET);
