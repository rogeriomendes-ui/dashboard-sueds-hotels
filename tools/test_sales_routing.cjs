assert.equal(blocked.targetSheet,routing.SELLERS_SHEET);
const kissyla = routing.normalizeDeskhotel({codigo:'CR29070361669',dataVenda:'12/09/2026',origin:'Site_Estabelecimento - Amanda Sales Melgaço',hotel:'SUEDS PLAZA',status:'Confirmada'});
assert.equal(kissyla.canal,'SITE');
assert.equal(kissyla.vendedor,'Amanda Melgaco');
assert.equal(kissyla.targetSheet,routing.SELLERS_SHEET);
assert.equal(routing.normalizeDeskhotel({...kissyla,codigo:'OUTRA'}).targetSheet,routing.SELLERS_SHEET);
