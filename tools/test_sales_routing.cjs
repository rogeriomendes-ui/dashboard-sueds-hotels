assert.equal(shop.hotel,'SUEDS EXPERIENCIAS');
assert.equal(shop.canal,'SITE');
assert.equal(shop.vendedor,'');
assert.equal(shop.targetSheet,routing.CHANNELS_SHEET);
assert.equal(routing.normalizeDeskhotel({dataVenda:'04/09/2026',origin:'Depto_Reservas',hotel:'SUEDS EXPERIENCIAS'}).targetSheet,routing.CHANNELS_SHEET);
const blocked = routing.normalizeDeskhotel({dataVenda:'12/09/2026',origin:'Depto_Reservas - Amanda Sales Melgaço',hotel:'SUEDS PLAZA',status:'Bloqueada'});
assert.equal(blocked.status,'Pendente');
